function esc(s) {
  return String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

function sourceLink(sourceId) {
  const s = SOURCES[sourceId];
  if (!s) return "";
  if (s.url) return `<a href="${esc(s.url)}" rel="nofollow">${esc(s.label)}</a> (${esc(s.org)})`;
  return `${esc(s.label)} (${esc(s.org)})`;
}

// Возвращает { kind: 'citation'|'disclaimer'|'disputed'|null, html }
// html — короткий блок для вставки под "п.к. NNNN" на странице дома, либо
// null, если для этого postcode_src ничего показывать не нужно (пусто/
// неизвестно).
function getPostcodeNote(postcodeSrc) {
  if (!postcodeSrc) return null;

  if (DISPUTED[postcodeSrc]) {
    const d = DISPUTED[postcodeSrc];
    return {
      kind: "disputed",
      html: `<div class="postcode-note postcode-note--disputed"><p class="postcode-note__title">⚠ ${esc(d.title)}</p>${d.html}</div>`,
    };
  }

  if (COMPUTED_NO_ALTERNATIVE[postcodeSrc]) {
    const { sourceId } = COMPUTED_NO_ALTERNATIVE[postcodeSrc];
    return {
      kind: "disclaimer",
      html: `<p class="postcode-note postcode-note--computed">Индекс вычислен нами, не взят напрямую из реестра — ${sourceLink(sourceId)}.
        Подробнее о методе: <a href="/o-dannyh/#metod-knn">как мы это считаем</a>.</p>`,
    };
  }

  if (CITATION[postcodeSrc]) {
    const { sourceId, note } = CITATION[postcodeSrc];
    const noteHtml = note ? ` <span class="postcode-note__extra">${esc(note)}</span>` : "";
    return { kind: "citation", html: `<p class="postcode-note postcode-note--citation">Источник: ${sourceLink(sourceId)}.${noteHtml}</p>` };
  }

  return null;
}

module.exports = { SOURCES, getPostcodeNote, sourceLink };
